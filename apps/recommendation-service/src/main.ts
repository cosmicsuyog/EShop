import 'dotenv/config';
import express from 'express';
import cookieParser from 'cookie-parser';
import cors from 'cors';
import { errorMiddleware } from '@packages/error-handler/error-middleware.js';
import router from './routes/recommendation.route.js';
const app = express(); app.use(cors({ origin: true, credentials: true })); app.use(express.json({ limit: '1mb' })); app.use(express.urlencoded({ extended: true, limit: '1mb' })); app.use(cookieParser());
app.get('/', (_req, res) => res.json({ service: 'recommendation-service', status: 'ok' }));
app.get('/health-check', (_req, res) => res.json({ service: 'recommendation-service', status: 'ok' }));
app.use('/api', router);
app.use(errorMiddleware);
app.listen(Number(process.env.RECOMMENDATION_SERVICE_PORT) || 6007, () => console.log('Recommendation service listening on port 6007'));
